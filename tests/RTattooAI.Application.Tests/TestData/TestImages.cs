    /// <summary>JPEG con cabecera SOF0 que declara 8x8 píxeles.</summary>
    public static byte[] Jpeg() =>
    [
        0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00,       // SOI + APP0/JFIF
