    ];

    /// <summary>WEBP con contenedor extendido (VP8X) que declara 4x4 píxeles.</summary>
    public static byte[] Webp()
    {
        byte[] bytes =
        [
            0x52, 0x49, 0x46, 0x46,                 // "RIFF"
            0x2A, 0x00, 0x00, 0x00,                 // tamaño del contenedor
            0x57, 0x45, 0x42, 0x50,                 // "WEBP"
            0x56, 0x50, 0x38, 0x58,                 // "VP8X"
            0x0A, 0x00, 0x00, 0x00,                 // tamaño del chunk
            0x00, 0x00, 0x00, 0x00,                 // banderas + reservado
            0x03, 0x00, 0x00,                       // ancho - 1  (=> 4)
            0x03, 0x00, 0x00,                       // alto  - 1  (=> 4)
            0x00, 0x00
        ];
        return bytes;
    }

    /// <summary>Contenido arbitrario que se hace pasar por imagen.</summary>
